"""터미널에서 동작하는 퀴즈 게임."""

MENU = """
========================================
            나만의 퀴즈 게임
========================================
1. 퀴즈 풀기
2. 퀴즈 추가
3. 퀴즈 목록
4. 점수 확인
5. 종료
========================================"""


def show_menu():
    print(MENU)


def main():
    while True:
        show_menu()
        choice = input("선택: ").strip()

        if choice == "5":
            print("게임을 종료합니다.")
            break
        elif choice in ("1", "2", "3", "4"):
            print("아직 구현되지 않은 기능입니다.")
        else:
            print("1부터 5 사이의 번호를 입력해 주세요.")


if __name__ == "__main__":
    main()
